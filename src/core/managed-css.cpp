#include "managed-css.h"

namespace sspot::core {

namespace {

constexpr std::string_view BLOCK_NOTE =
	"/* Generated by Speaker Spotlight. Changes inside this block are overwritten when you apply. */";

size_t count_occurrences(std::string_view text, std::string_view needle)
{
	size_t count = 0;
	for (size_t pos = text.find(needle); pos != std::string_view::npos;
	     pos = text.find(needle, pos + needle.size()))
		++count;
	return count;
}

std::string make_block(std::string_view generated)
{
	std::string block;
	block += BLOCK_BEGIN;
	block += '\n';
	block += BLOCK_NOTE;
	block += '\n';
	block += generated;
	if (!generated.empty() && generated.back() != '\n')
		block += '\n';
	block += BLOCK_END;
	return block;
}

} // namespace

BlockState inspect_block(std::string_view css)
{
	const size_t begins = count_occurrences(css, BLOCK_BEGIN);
	const size_t ends = count_occurrences(css, BLOCK_END);
	if (begins == 0 && ends == 0)
		return BlockState::Absent;
	if (begins != 1 || ends != 1)
		return BlockState::Broken;
	return css.find(BLOCK_BEGIN) < css.find(BLOCK_END) ? BlockState::Intact : BlockState::Broken;
}

std::optional<std::string> replace_block(std::string_view css, std::string_view generated)
{
	const std::string block = make_block(generated);

	switch (inspect_block(css)) {
	case BlockState::Absent: {
		std::string result(css);
		while (!result.empty() && (result.back() == '\n' || result.back() == '\r'))
			result.pop_back();
		if (!result.empty())
			result += '\n';
		result += block;
		result += '\n';
		return result;
	}
	case BlockState::Intact: {
		const size_t begin = css.find(BLOCK_BEGIN);
		const size_t end = css.find(BLOCK_END) + BLOCK_END.size();
		std::string result;
		result.reserve(css.size() + block.size());
		result.append(css.substr(0, begin));
		result += block;
		result.append(css.substr(end));
		return result;
	}
	case BlockState::Broken:
		break;
	}
	return std::nullopt;
}

} // namespace sspot::core
